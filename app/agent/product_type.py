"""금융상품 유형 판별 — 금소법 제3조의 네 유형.

**왜 유형 축을 따로 두는가.**

`classifier.CATEGORIES` 10종은 서로 다른 축을 섞어 놓았다. `보험`과 `불완전판매`는
배타적이 아니다 — 보험 불완전판매 사건은 둘 다다. 배타적이지 않은 것을 하나만
고르라고 하면 모델이 아무리 좋아도 정답률에 천장이 생긴다. 금감원 사례집 라벨로
재니 62.5%였고, 후보 회수율 천장이 70.8%였다.

**축을 하나로 좁히면 달라진다.** 같은 정답지에서 제3조의 상품유형 하나만 물었을 때
(`scripts/experiment_product_facet.py`, 200건):

    후보 회수율(recall@2)   96.0%
    sLLM이 하나 고르면      92.5%
    Qwen2.5 7B로 고르면     90.0%   ← 큰 모델이 더 나빴다

**그래서 고르지 않는다.** 제3조는 단서로 이렇게 정한다 — *"개별 금융상품이 둘 이상에
해당하는 속성이 있는 경우에는 해당 상품유형에 각각 속하는 것으로 본다."* 조문이
다중 소속을 전제하는데 하나로 좁힐 이유가 없다. 상위 2개를 그대로 돌려주면
**정답 포함률이 96.0%**이고, sLLM 호출이 없어 결정론적이며 빠르다.

이 값은 **청약철회 기간을 고르는 데 쓴다.** 제46조①이 유형별로 기간을 달리 정하기
때문이다(1호 보장성 15일 · 2호 투자성 7일 · 3호 대출성 14일). 유형을 잘못 집으면
그 카드가 사라지는데, 두 개를 함께 보여 주면 사라지지 않는다. 짧은 쪽이 먼저
도래하므로 사용자가 놓치는 방향으로 틀리지 않는다.

측정 환경 주의: 정답지의 입력은 사례 제목(법률 문어체)이다. 실사용 구어체와 문체가
달라 96.0%도 대리 지표다.
"""
from __future__ import annotations

import numpy as np

from app.search import embedder

# 금소법 제3조 각 호. 설명은 조문과 금감원 사례집의 장·절 이름에서 가져왔다 —
# 우리가 무엇을 빠뜨렸는지 판단하지 않으려고 감독당국의 어휘를 그대로 쓴다.
PRODUCT_TYPES: dict[str, str] = {
    "보장성 상품": "보험상품. 생명보험·손해보험·자동차보험, 보험금 지급책임, 보험계약 해지, "
                  "계약 전 알릴 의무 위반, 재해·장해·수술·암 진단 인정 여부, 대인배상·대물배상",
    "투자성 상품": "금융투자상품. 펀드·신탁·ELS·ELF·파생결합증권·주식·선물옵션·부동산펀드, "
                  "설명의무 위반과 부당권유, 펀드 환매, 매매주문 착오, 반대매매, 임의매매",
    "대출성 상품": "대출, 신용카드·시설대여(리스)·연불판매·할부금융. "
                  "담보책임과 보증책임, 포괄근저당·한정근저당, 제3자 담보제공, 연대보증과 "
                  "보증의사 확인, 근질권, 연체와 상환, 중도상환수수료, 신용카드 부정사용",
    "예금성 상품": "예금과 적금. 계좌 개설과 입금, 금리 적용, 예금 지급과 해지, "
                  "예금 지급정지·상계·착오송금, 수표대금 지급",
}

_NAMES = list(PRODUCT_TYPES)
_vecs: np.ndarray | None = None

# 상위 몇 개를 돌려줄지. 2에서 정답 포함률 96.0%, 3이면 98.5%지만 무관한 청약철회
# 카드가 하나 더 붙는다. 카드가 빠지는 것이 더 나쁘다는 원칙(09_모델_평가 §3)에서도
# 2가 균형점이다 — 4종 중 절반이면 사용자가 가려 읽을 수 있다.
TOP_K = 2


def _unit(v: np.ndarray) -> np.ndarray:
    n = np.linalg.norm(v, axis=-1, keepdims=True)
    return v / np.where(n == 0, 1, n)


def infer(text: str, top: int = TOP_K) -> list[str]:
    """해당될 수 있는 상품유형을 유사도 순으로. **하나로 좁히지 않는다.**

    sLLM을 부르지 않는다. 부르면 하나를 고르게 되어 92.5%로 떨어지고, 이 값은
    청약철회 카드를 고르는 데 쓰이므로 좁히는 순간 카드가 사라진다.
    """
    global _vecs
    if _vecs is None:
        _vecs = _unit(embedder.embed([f"{n}: {d}" for n, d in PRODUCT_TYPES.items()]))
    qv = _unit(embedder.embed([text])[0])
    order = np.argsort(_vecs @ qv)[::-1]
    return [_NAMES[i] for i in order[:top]]
