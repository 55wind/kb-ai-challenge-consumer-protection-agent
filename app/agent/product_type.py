_MEANS_WORDS: dict[str, list[str]] = {
    "예금성 상품": ["송금", "계좌이체", "통장", "수표", "입금", "출금", "예치"],
    "대출성 상품": ["상환", "연체", "원리금", "이자", "채무", "변제"],
    "투자성 상품": ["매매", "매수", "매도", "주문", "환매", "수익증권"],
    "보장성 상품": ["보험금", "보험료", "보험증권", "고지의무", "보험사고"],
}
_LEXICON: dict[str, str] = {
    **_STATUTE_NOUNS,
    **{w: kind for kind, ws in _MEANS_WORDS.items() for w in ws},
}


def _lexical(text: str) -> str | None:
    """낱말 빈도로 상품유형을 정한다. 정하지 못하면 None.

    동점이면 None을 돌려준다 — 조문 낱말이 두 유형을 같은 무게로 가리키면
    제3조 단서(중복 귀속)에 해당해 하나로 좁힐 근거가 없다.
    """
    tally: dict[str, int] = {}
    for word, kind in _LEXICON.items():
        n = text.count(word)
        if n:
            tally[kind] = tally.get(kind, 0) + n
    if not tally:
        return None
    ranked = sorted(tally.items(), key=lambda kv: -kv[1])
    if len(ranked) > 1 and ranked[0][1] == ranked[1][1]:
        return None
    return ranked[0][0]

# 상위 몇 개를 돌려줄지. 2에서 정답 포함률 96.0%, 3이면 98.5%지만 무관한 청약철회
# 카드가 하나 더 붙는다. 카드가 빠지는 것이 더 나쁘다는 원칙(09_모델_평가 §3)에서도
# 2가 균형점이다 — 4종 중 절반이면 사용자가 가려 읽을 수 있다.
TOP_K = 2


def _unit(v: np.ndarray) -> np.ndarray:
    n = np.linalg.norm(v, axis=-1, keepdims=True)
    return v / np.where(n == 0, 1, n)


def infer(text: str, top: int = TOP_K) -> list[str]:
    """해당될 수 있는 상품유형을 순서대로. **하나로 좁히지 않는다.**

    sLLM을 부르지 않는다. 부르면 하나를 고르게 되어 92.5%로 떨어지고, 이 값은
    청약철회 카드를 고르는 데 쓰이므로 좁히는 순간 카드가 사라진다.

    1순위는 **낱말이 정할 수 있으면 낱말이** 정하고(위 `_lexical` 설명), 나머지
    순위는 임베딩 순서를 그대로 잇는다. 낱말이 못 정하면 전부 임베딩이다.
    """
    global _vecs
    if _vecs is None:
        _vecs = _unit(embedder.embed([f"{n}: {d}" for n, d in PRODUCT_TYPES.items()]))
    qv = _unit(embedder.embed([text])[0])
    order = np.argsort(_vecs @ qv)[::-1]
    ranked = [_NAMES[i] for i in order]

    lexical = _lexical(text)
    if lexical and lexical != ranked[0]:
        # 낱말이 정한 것을 앞에 세우되 **임베딩 순서를 지운 것이 아니다** —
        # 뒤 순위는 그대로 남아 top-2가 좁아지지 않는다.
        ranked = [lexical] + [x for x in ranked if x != lexical]
    return ranked[:top]
