"""금융상품 유형 판별 — 금소법 제3조의 네 유형.

**왜 유형 축을 따로 두는가.**

`classifier.CATEGORIES` 10종은 서로 다른 축을 섞어 놓았다. `보험`과 `불완전판매`는
배타적이 아니다 — 보험 불완전판매 사건은 둘 다다. 배타적이지 않은 것을 하나만
고르라고 하면 모델이 아무리 좋아도 정답률에 천장이 생긴다. 금감원 사례집 라벨로
재니 62.5%였고, 후보 회수율 천장이 70.8%였다.

**축을 하나로 좁히면 달라진다.** 같은 정답지에서 제3조의 상품유형 하나만 물었을 때
(`scripts/experiment_product_facet.py`, 200건):

    후보 회수율(recall@2)   96.0%
    sLLM이 하나 고르면      92.5%
    Qwen2.5 7B로 고르면     90.0%   ← 큰 모델이 더 나빴다

**그래서 고르지 않는다.** 제3조는 단서로 이렇게 정한다 — *"개별 금융상품이 둘 이상에
해당하는 속성이 있는 경우에는 해당 상품유형에 각각 속하는 것으로 본다."* 조문이
다중 소속을 전제하는데 하나로 좁힐 이유가 없다. 상위 2개를 그대로 돌려주면
**정답 포함률이 96.0%**이고, sLLM 호출이 없어 결정론적이며 빠르다.

이 값은 **청약철회 기간을 고르는 데 쓴다.** 제46조①이 유형별로 기간을 달리 정하기
때문이다(1호 보장성 15일 · 2호 투자성 7일 · 3호 대출성 14일). 유형을 잘못 집으면
그 카드가 사라지는데, 두 개를 함께 보여 주면 사라지지 않는다. 짧은 쪽이 먼저
도래하므로 사용자가 놓치는 방향으로 틀리지 않는다.

측정 환경 주의: 정답지의 입력은 사례 제목(법률 문어체)이다. 실사용 구어체와 문체가
달라 96.0%도 대리 지표다.
"""
